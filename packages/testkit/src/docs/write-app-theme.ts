// Writes the app's first-paint theme (packages/app/src/theme/fallback.generated.ts): pi's dark theme
// as hex, used until the hub sends the user's theme (theme_get):
//   node packages/testkit/src/docs/write-app-theme.ts

import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { themeColors } from "#hub/themes.ts";

export const APP_THEME_FILE = join(import.meta.dirname, "..", "..", "..", "app", "src", "theme", "fallback.generated.ts");

export async function appThemeSource(): Promise<string> {
  const theme = await themeColors(mkdtempSync(join(tmpdir(), "theme-")), "dark");
  const entries = Object.entries(theme.colors)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([token, hex]) => `  ${token}: "${hex}",`);
  return [
    "// Generated by packages/testkit/src/docs/write-app-theme.ts from pi's dark theme: do not edit.",
    "// The colors until the node sends the user's theme (theme_get).",
    "",
    "export const FALLBACK_COLORS = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(APP_THEME_FILE, await appThemeSource());
  process.stdout.write(`${APP_THEME_FILE}\n`);
}
